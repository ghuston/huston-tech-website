// The generated list of form files the Worker bundles (src/forms/registry.generated.ts). `registrySource` is the one
// generator: `npm run sync:config` writes the file with it, the site editor writes it when a form is added, and the
// change scope check compares the committed file with its output. Import-free.
export const REGISTRY_PATH = "src/forms/registry.generated.ts";

/** The text of the registry for these form ids: sorted, one JSON import each, so the same ids always give the same file. */
export function registrySource(ids: readonly string[]): string {
  const sorted = [...new Set(ids)].sort((a, b) => (a < b ? -1 : a > b ? 1 : 0));
  const name = (id: string) => `f_${id.replace(/-/g, "_")}`;
  const imports = sorted.map((id) => `import ${name(id)} from "../content/forms/${id}.json" with { type: "json" };\n`).join("");
  const entries = sorted.map((id) => `  { id: "${id}", data: ${name(id)} },\n`).join("");
  return `// Generated by \`npm run sync:config\` from src/content/forms/*.json. Do not edit by hand.
${imports}
export const formFiles: readonly { id: string; data: unknown }[] = [
${entries}];
`;
}

/** The form ids a registry source lists, in file order: the inverse of `registrySource`. */
export function registryIds(source: string): string[] {
  return [...source.matchAll(/^ {2}\{ id: "([^"]+)", data: /gm)].map((match) => match[1] as string);
}
