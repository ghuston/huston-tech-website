const ORDER = ["T1-hideout", "T2-octherapy", "T3-ifc"];

export function getTestimonials(placement: TestimonialPlacement): Testimonial[] {
  return testimonials
    .filter((t) => t.approved && t.placements.includes(placement))
    .sort((a, b) => ORDER.indexOf(a.id) - ORDER.indexOf(b.id));
}

export function getTestimonialById(id: string): Testimonial {
  const found = testimonials.find((t) => t.id === id && t.approved);
  if (!found) throw new Error(`Approved testimonial not found: ${id}`);
  return found;
}
